//! Loading `.vst3` binaries and reading their plugin factories.
//!
//! Derived from soundCraft's `vst3-host` (`ffi.rs`), MIT OR Apache-2.0; see
//! `third_party/soundcraft/`. What changed: every call into plugin code goes through the
//! exception-catching shim (including the module entry and exit), the factory gets
//! `IPluginFactory3::setHostContext`, and errors are [`PluginError`].

